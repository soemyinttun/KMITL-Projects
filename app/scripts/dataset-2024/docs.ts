/** Builds docs/dataset-2024.md from the generated data, so every figure in it matches the dataset. */
import type { Data } from '../../src/types.ts'
import * as C from './config.ts'
import { ITINERARIES } from './itineraries.ts'
import { byOrigin, byPackage, byService, byStop, grandTotal, monthly } from './summary.ts'

export const ks = (n: number) => `${n.toLocaleString('en-US')} Ks`
export const lakh = (n: number) => (n / C.LAKH).toLocaleString('en-US', { maximumFractionDigits: 2 })
const pct = (n: number, of: number) => `${((n / of) * 100).toFixed(1)}%`
const table = (head: string[], rows: (string | number)[][]) =>
  [`| ${head.join(' | ')} |`, `|${head.map(() => '---').join('|')}|`, ...rows.map((r) => `| ${r.join(' | ')} |`)].join('\n')

export function datasetMarkdown(d: Data): string {
  const total = grandTotal(d)
  const months = monthly(d)
  const svc = byService(d)
  const peakProfit = months.filter((m) => m.peak).reduce((s, m) => s + m.total.profit, 0)
  const itin = new Map(ITINERARIES.map((i) => [i.packageId, i]))

  return `# SSM Travel Ops — 2024 demo dataset

> **Synthetic demo data.** Customers, phone numbers and transactions are invented. **All prices, costs,
> fees and fares are estimates**, not SSM Travel & Tours' real prices (facebook.com/ssm.gaya could not be
> read without logging in). Replace them with real figures — see [Changing the numbers](#changing-the-numbers).
>
> This file is generated by \`app/scripts/generate-dataset-2024.ts\`. Do not edit it by hand.

## At a glance

| Item | Value |
|---|---|
| Period | 1 Jan – 31 Dec ${C.YEAR} |
| Currency | Myanmar kyat (Ks). 1 lakh = 100,000 Ks |
| **Total profit** | **${ks(total.profit)} (${lakh(total.profit)} lakh)** |
| Total revenue | ${ks(total.revenue)} (${lakh(total.revenue)} lakh) |
| Profit in peak months (Apr, May, Sep–Dec) | ${ks(peakProfit)} (${pct(peakProfit, total.profit)}) |
| Customers | ${d.customers.length} |
| Bookings (all statuses) | ${d.bookings.length} |
| Visa cases / passport cases / air tickets | ${d.visas.length} / ${d.passports.length} / ${d.tickets.length} |

"Profit" means price − cost (the app's **Gross margin**). Office costs, salaries and tax are not included.

## Files

| File | What it is |
|---|---|
| \`app/src/data/dataset-2024.json\` | The dataset the app loads (same format as Settings → Backup) |
| \`docs/dataset-2024/SSM-Travel-Ops-2024.xlsx\` | Excel workbook: every table plus summaries, formatted |
| \`docs/dataset-2024/*.csv\` | One CSV per table, plus \`monthly_summary.csv\` |

## Profit by month

${table(
  ['Month', 'Peak', 'Package', 'Visa', 'Passport', 'Air ticket', 'Total profit', 'Lakh', 'Share'],
  [
    ...months.map((m) => [m.name, m.peak ? '★' : '', ...(['Package', 'Visa', 'Passport', 'Air ticket'] as const).map((s) => ks(m.byService[s].profit)), `**${ks(m.total.profit)}**`, lakh(m.total.profit), pct(m.total.profit, total.profit)]),
    ['**Total**', '', ...(['Package', 'Visa', 'Passport', 'Air ticket'] as const).map((s) => `**${ks(svc[s].profit)}**`), `**${ks(total.profit)}**`, `**${lakh(total.profit)}**`, '100%'],
  ],
)}

Sales are dated by booking/sale date (bookings), decision date (visa, passport) and ticket date, the same as the app.

## Profit by service

${table(
  ['Service', 'Revenue', 'Profit', 'Share of profit'],
  (['Package', 'Visa', 'Passport', 'Air ticket'] as const).map((s) => [s, ks(svc[s].revenue), ks(svc[s].profit), pct(svc[s].profit, total.profit)]),
)}

## Packages (estimated prices, per person)

${table(
  ['ID', 'Package', 'Days', 'Price', 'Cost', 'Profit / person', 'Margin', 'Booked', 'Travellers', 'Enquiries', 'Cancelled', 'Profit'],
  byPackage(d).map((r) => {
    const p = d.packages.find((x) => x.id === r.id)!
    return [r.id, r.name, r.days, ks(p.price), ks(p.cost), ks(p.price - p.cost), pct(p.price - p.cost, p.price), r.bookings, r.pax, r.enquiries, r.cancelled, ks(r.profit)]
  }),
)}

Package prices include flights and accommodation. Popularity: 8-day and 12-day sell most, then 5-day, then
15-day. Thailand has exactly two group trips (April and October holidays).

## Itineraries

${d.packages.map((p) => {
  const i = itin.get(p.id)!
  return `### ${p.id} — ${p.name}${i.source === 'placeholder' ? ' *(placeholder)*' : ''}

Stops (used by the heatmap): ${p.stops.join(' → ')}
${i.note ? `\n> **Note:** ${i.note}\n` : ''}
${i.days.map((x) => `- **Day ${x.day}: ${x.title}**${x.detail ? ` — ${x.detail}` : ''}`).join('\n')}`
}).join('\n\n')}

## Where travellers go (heatmap)

Each booking counts once for **every stop** on its itinerary, so the map shows the whole circuit.

${table(['Place', 'Bookings passing through', 'Travellers'], byStop(d).map((r) => [r.place, r.bookings, r.travellers]))}

## Where customers come from

${table(
  ['Origin', 'Customers', 'Bookings', 'Travellers', 'Package revenue', 'Package profit'],
  byOrigin(d).map((r) => [r.origin, r.customers, r.bookings, r.travellers, ks(r.revenue), ks(r.profit)]),
)}

Rakhine is a state, not a town; the map plots it at Sittwe.

## Assumptions

- **Exchange rate:** the app stores kyat. USD is display-only, using ${C.FX_ESTIMATE.toLocaleString('en-US')} Ks per USD (an estimate; change it in Settings).
- **Visa fees:** the fee charged includes the government fee; cost = government fee + processing. Profit is the service margin only.
- **Air tickets** here are stand-alone ticket sales (package prices already include flights). Profit = commission. Airlines and fares are examples.
- **Enquiries** that did not convert and **cancelled** bookings are included to show demand; they earn nothing.
- Every 2024 record is finished: bookings are completed, visas delivered (two rejected), passports collected.
- Customer passports are valid for at least 6 months after every 2024 trip. Some expire within 6 months of today, so the Customers page highlights them.

## Data dictionary

All money columns are whole kyat. Dates are \`YYYY-MM-DD\`.

| Table / CSV | Column | Meaning |
|---|---|---|
| customers | id, name, phone, township, passportExpiry | Customer; \`township\` is the origin used by the origin heatmap |
| packages | id, name, country, days, price, cost, stops | Price and cost per person; \`stops\` separated by \`→\` in CSV |
| bookings | id, customerId, packageId, destination, departDate, pax, status, createdAt | \`createdAt\` is the sale date; revenue = price × pax for completed/confirmed |
| visas | id, customerId, kind, stage, appliedAt, decidedAt, fee, cost | \`kind\` = visa country; profit counted when Approved/Delivered |
| passports | id, customerId, kind, stage, appliedAt, decidedAt, fee, cost | \`kind\` = New/Renewal/Lost/Damaged; profit counted when Ready/Collected |
| tickets | id, customerId, direction, from, to, airline, date, fare, commission | Revenue = fare, profit = commission |
| monthly_summary | month, peak, <service>_revenue, <service>_profit, total_revenue, total_profit | One row per month plus a TOTAL row |

## Loading it into the app

- **Fresh install / empty app:** the app loads this dataset automatically.
- **Existing data:** Settings → *Reset to demo data* (replaces everything), or Settings → *Restore backup* with \`dataset-2024.json\`.
- Choose **2024** in the date-range menu (it is the default) to see the year.

## Changing the numbers

1. Edit prices/costs, monthly weights or service shares in \`app/scripts/dataset-2024/config.ts\`
   (itineraries in \`itineraries.ts\`).
2. Run \`npm run generate:dataset\` in \`app/\`. It regenerates the JSON, CSVs, workbook and this file, and stops with an
   error if total profit is not exactly ${ks(C.TARGET_PROFIT)} (change \`TARGET_PROFIT\` too if the target changes).
3. Run \`npm test\` — the dataset tests check the totals, peak months, package mix and origin ranking.
`
}
